"""mint_tse_t2_tra.py - t2_tse_tra (Turbo Spin Echo · 2D · CPMG)

Console protocol generated by the MINT web-app (PyPulseq).
Reference script: tse.txt (TSE_centered4)
Scanner: Disc Scanner (0.55 T)
ETL 4 | TE 80 ms | TR 5000 ms | FoV 256 mm x 100 % | 2 x 2 mm | slice 4 mm

Running this script writes mint_tse_t2_tra.seq, mint_tse_t2_tra_report.txt and (with
save_plots=True) the diagrams next to the script.
Its MATLAB twin is mint_tse_t2_tra.m: the same blocks, names and checks.
"""
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

import pypulseq as pp


class MintValidator:
    """MINT timing and physical checks for one sequence build.

    Two kinds of finding:

    * WARNINGS are collected and printed at the top of the run log. The
      sequence still builds - it is legal Pulseq - but it will not time the
      way it reads.
    * ERRORS raise ValueError before the offending block reaches the
      sequence: the combination is physically impossible.
    """

    def __init__(self, system):
        self.system = system
        # A lobe is routinely split in half: TE runs to the MIDDLE of the
        # readout lobe, a rephaser carries HALF the selection area. So every
        # lobe, TE and TR must be a whole number of DOUBLE gradient rasters -
        # 20 us on a 10 us raster. Otherwise the half lands off the raster and
        # a ceil() further down shifts everything that follows it.
        self.lobe_raster = 2 * system.grad_raster_time
        self.warnings = []
        self.n_blocks = 0
        self.clock = 0.0                    # [s] start time of the next block
        self.slice_ramp_down_start = None   # [s] absolute; set by each RF block

    # -- raster arithmetic -------------------------------------------------
    @staticmethod
    def is_multiple(value, raster):
        ratio = value / raster
        return abs(ratio - round(ratio)) < 1e-6

    @staticmethod
    def round_to(value, raster):
        return np.round(value / raster) * raster

    @staticmethod
    def ceil_to(value, raster):
        # Round first: 2.56e-3 / 2e-5 is 128.00000000000003 in floating
        # point, and a bare ceil() would turn that into 129.
        return np.ceil(np.round(value / raster, 6)) * raster

    @staticmethod
    def floor_to(value, raster):
        return np.floor(np.round(value / raster, 6)) * raster

    def warn(self, text):
        if text not in self.warnings:  # a check inside a loop reports once
            self.warnings.append(text)

    # -- raster checks (warnings) ------------------------------------------
    def check_adc_dwell(self, dwell, name='ADC dwell'):
        """The dwell must be an exact integer multiple of adc_raster_time."""
        raster = self.system.adc_raster_time
        if self.is_multiple(dwell, raster):
            return True
        self.warn(
            f'{name} = {dwell * 1e9:.2f} ns is NOT an integer multiple of adc_raster_time '
            f'({raster * 1e9:.0f} ns): the scanner cannot sample at that rate. '
            f'Nearest valid dwell below it: {self.floor_to(dwell, raster) * 1e9:.0f} ns.'
        )
        return False

    def check_adc(self, adc, name='adc'):
        """Dwell on the ADC raster, sample count a multiple of the divisor."""
        self.check_adc_dwell(adc.dwell, f'{name}.dwell')
        divisor = int(getattr(self.system, 'adc_samples_divisor', 1) or 1)
        if adc.num_samples % divisor:
            self.warn(
                f'{name}: {adc.num_samples} samples is not a multiple of adc_samples_divisor '
                f'({divisor}); some scanners reject it.'
            )

    def check_lobes(self, lobes):
        """Every gradient lobe must last a whole number of 2 * grad_raster_time."""
        for name, grad in lobes.items():
            if grad.type == 'trap':
                duration = grad.rise_time + grad.flat_time + grad.fall_time
            else:
                duration = grad.shape_dur
            if not self.is_multiple(duration, self.lobe_raster):
                self.warn(
                    f'{name}: duration {duration * 1e6:.1f} us is not a multiple of '
                    f'2 * grad_raster_time ({self.lobe_raster * 1e6:.0f} us). Half of it falls off the '
                    f'gradient raster, so splitting it forces a ceil() that drifts the timing. '
                    f'Use {self.ceil_to(duration, self.lobe_raster) * 1e6:.0f} us.'
                )

    def check_timing_parameter(self, name, value):
        """TE, TR and TI must be whole numbers of 2 * grad_raster_time."""
        if not self.is_multiple(value, self.lobe_raster):
            nearest = self.round_to(value, self.lobe_raster)
            self.warn(
                f'{name} = {value * 1e3:.4f} ms is not a multiple of 2 * grad_raster_time '
                f'({self.lobe_raster * 1e6:.0f} us). Its half falls off the gradient raster, so the '
                f'delays are rounded and the sequence plays at a slightly different {name}. '
                f'Nearest valid value: {nearest * 1e3:.2f} ms.'
            )

    def check_b1(self, name, rf, max_b1):
        """Peak B1 of a pulse against the scanner limit [T]."""
        peak = np.max(np.abs(rf.signal)) / self.system.gamma  # Hz -> T
        if peak > max_b1 * (1 + 1e-9):
            self.warn(
                f'{name}: peak B1 {peak * 1e6:.2f} uT exceeds max_b1 ({max_b1 * 1e6:.2f} uT). '
                f'Lengthen the pulse or lower the flip angle.'
            )

    # -- physical checks (errors) ------------------------------------------
    def check_block(self, *events):
        """Reject an impossible RF / gradient / ADC combination.

        Called for every block BEFORE it is built. Raises ValueError.
        """
        flat = []
        for event in events:
            flat.extend(event if isinstance(event, (list, tuple)) else [event])
        flat = [e for e in flat if e is not None and hasattr(e, 'type')]

        self.n_blocks += 1
        where = f'Block {self.n_blocks} (t = {self.clock * 1e3:.3f} ms)'
        tol = 1e-9
        rf = [e for e in flat if e.type == 'rf']
        adc = [e for e in flat if e.type == 'adc']
        grads = [e for e in flat if e.type in ('trap', 'grad')]

        if len(rf) > 1:
            raise ValueError(f'{where}: {len(rf)} RF pulses in one block. A block holds at most one.')
        if len(adc) > 1:
            raise ValueError(f'{where}: {len(adc)} ADC events in one block. A block holds at most one.')
        if rf and adc:
            raise ValueError(
                f'{where}: RF and ADC in the same block. The scanner cannot transmit and '
                f'receive at once - put the readout in its own block.'
            )
        for channel in 'xyz':
            n_on_channel = sum(1 for g in grads if g.channel == channel)
            if n_on_channel > 1:
                raise ValueError(
                    f'{where}: {n_on_channel} gradient events on the {channel} axis. They would '
                    f'overlap - combine them into one event or split them into two blocks.'
                )

        if rf:
            rf_start = rf[0].delay
            rf_end = rf[0].delay + rf[0].shape_dur
            selection = [g for g in grads if g.channel == 'z' and g.type == 'trap']
            if selection:
                plateau_start = selection[0].delay + selection[0].rise_time
                plateau_end = plateau_start + selection[0].flat_time
                if rf_start < plateau_start - tol or rf_end > plateau_end + tol:
                    raise ValueError(
                        f'{where}: the RF pulse plays from {rf_start * 1e6:.1f} to {rf_end * 1e6:.1f} us '
                        f'but the slice-selection plateau (flat_time) spans {plateau_start * 1e6:.1f} to '
                        f'{plateau_end * 1e6:.1f} us. RF on a gradient ramp excites a distorted '
                        f'slice: delay the RF or lengthen the plateau.'
                    )
                self.slice_ramp_down_start = self.clock + plateau_end
            else:
                # No selection lobe: nothing in-plane may start under the pulse.
                self.slice_ramp_down_start = self.clock + rf_end

        if self.slice_ramp_down_start is not None:
            for g in grads:
                if g.channel == 'z':
                    continue
                start = self.clock + g.delay
                if start < self.slice_ramp_down_start - tol:
                    raise ValueError(
                        f'{where}: the g{g.channel} event starts at {start * 1e6:.1f} us, before the '
                        f'slice-selection ramp-down begins at {self.slice_ramp_down_start * 1e6:.1f} us. '
                        f'Phase-encoding and readout-prephasing lobes may start with the ramp-down '
                        f'or after it, never under the RF pulse.'
                    )

        self.clock += pp.calc_duration(*flat) if flat else 0.0

    def guard(self, add_block):
        """Wrap seq.add_block so every block is checked before it is built."""

        def checked_add_block(*events):
            self.check_block(*events)
            add_block(*events)

        return checked_add_block

    def report(self):
        """Lines for the run log: a banner when anything was flagged."""
        if not self.warnings:
            return [
                'MINT validation passed: ADC dwell, gradient-lobe rasters, TE/TR rasters, '
                'RF on the slice-selection plateau and block combinations.'
            ]
        banner = '!' * 78
        lines = [banner, f'MINT VALIDATION: {len(self.warnings)} WARNING(S)']
        lines += [f'WARNING: {text}' for text in self.warnings]
        lines.append(banner)
        return lines


def make_lobe_on_raster(channel, area, system, lobe_raster):
    """Shortest trapezoid for `area`, stretched to a whole number of lobe rasters.

    pp.make_trapezoid(area=...) alone returns the shortest lobe on the GRADIENT
    raster, which is an odd number of rasters about half the time. Stretching
    it to the lobe raster (2 * grad_raster_time) keeps its half on the raster.
    """
    lobe = pp.make_trapezoid(channel=channel, area=area, system=system)
    shortest = pp.calc_duration(lobe)
    duration = np.ceil(np.round(shortest / lobe_raster, 6)) * lobe_raster
    if duration - shortest > 1e-9:
        lobe = pp.make_trapezoid(channel=channel, area=area, duration=duration, system=system)
    return lobe


def main(
    plot: bool = False,
    test_report: bool = True,
    write_seq: bool = True,
    save_plots: bool = False,
    save_report: bool = True,
    seq_filename: str = 'mint_tse_t2_tra.seq',
):
    """Turbo spin echo, 2D, CPMG, centred interleaved phase encoding."""
    # --- Acquisition parameters -------------------------------------------
    etl = 4

    fov_x = 0.256  # [m]
    fov_y = 0.256  # [m]

    resolution_x = 2  # [mm]
    resolution_y = 2  # [mm]

    n_x = round(1000 * fov_x / resolution_x)
    n_y = round(1000 * fov_y / resolution_y)

    assert n_y % etl == 0, 'n_y must be divisible by ETL.'
    assert etl % 2 == 0, 'ETL must be even.'

    n_excitations = n_y // etl

    slice_thickness = 4e-3  # [m]

    te = 80e-3  # [s] effective TE
    tr = 5000e-3  # [s]

    center_echo = etl // 2
    esp = te / center_echo

    delta_kx = 1 / fov_x
    delta_ky = 1 / fov_y

    readout_time = 1.28e-3
    pre_time = 2e-3

    spoiler_time = 1e-3
    spoiler_area = 16 / fov_x
    spoiler_delay = 1e-3

    # --- System limits (Disc Scanner) ----------------------------------
    system = pp.Opts(
        max_grad=22,
        grad_unit='mT/m',
        max_slew=100,
        slew_unit='T/m/s',
        rf_ringdown_time=20e-6,
        rf_dead_time=100e-6,
        adc_dead_time=10e-6,
        grad_raster_time=10e-6,
        rf_raster_time=1e-6,
        adc_raster_time=100e-9,
        block_duration_raster=10e-6,
        B0=0.55,
    )
    max_b1 = 22e-6  # [T] peak B1 the scanner allows

    seq = pp.Sequence(system)
    raster = system.block_duration_raster

    # MINT validation: every block is checked before it reaches the sequence.
    mint = MintValidator(system)
    seq.add_block = mint.guard(seq.add_block)
    mint.check_timing_parameter('TE', te)
    mint.check_timing_parameter('TR', tr)
    mint.check_timing_parameter('ESP', esp)

    # --- RF pulses - CPMG -------------------------------------------------
    rf90, gz_imaging_slice_selection_lobe, _ = pp.make_sinc_pulse(
        flip_angle=np.pi / 2,
        system=system,
        duration=3e-3,
        slice_thickness=slice_thickness,
        apodization=0.5,
        time_bw_product=4,
        use='excitation',
        return_gz=True,
    )

    rf180, gz_refocusing_slice_selection_lobe, _ = pp.make_sinc_pulse(
        flip_angle=np.pi,
        system=system,
        duration=3e-3,
        slice_thickness=slice_thickness,
        apodization=0.5,
        time_bw_product=4,
        use='refocusing',
        return_gz=True,
    )

    rf90.phase_offset = 0
    rf180.phase_offset = np.pi / 2

    mint.check_b1('rf90', rf90, max_b1)
    mint.check_b1('rf180', rf180, max_b1)

    # --- Slice rephasing --------------------------------------------------
    gz_slice_selection_rephasing_lobe = pp.make_trapezoid(
        channel='z', area=-0.5 * gz_imaging_slice_selection_lobe.area, duration=pre_time, system=system)

    # --- Readout ----------------------------------------------------------
    gx_imaging_readout_lobe = pp.make_trapezoid(
        channel='x', flat_area=n_x * delta_kx, flat_time=readout_time, system=system)

    adc = pp.make_adc(
        num_samples=n_x, duration=readout_time, delay=gx_imaging_readout_lobe.rise_time, system=system)
    adc.phase_offset = 0

    # Balanced readout gradients for every echo
    gx_imaging_readout_prephasing_lobe = pp.make_trapezoid(
        channel='x', area=-0.5 * gx_imaging_readout_lobe.area, duration=pre_time, system=system)
    gx_imaging_readout_rewinding_lobe = pp.make_trapezoid(
        channel='x', area=-0.5 * gx_imaging_readout_lobe.area, duration=pre_time, system=system)

    # --- Symmetric crushers around every 180 ------------------------------
    gx_imaging_crusher = pp.make_trapezoid(
        channel='x', area=spoiler_area, duration=spoiler_time, system=system)
    gz_imaging_crusher = pp.make_trapezoid(
        channel='z', area=spoiler_area, duration=spoiler_time, system=system)

    mint.check_adc(adc)
    mint.check_lobes({
        'gz_imaging_slice_selection_lobe': gz_imaging_slice_selection_lobe,
        'gz_refocusing_slice_selection_lobe': gz_refocusing_slice_selection_lobe,
        'gz_slice_selection_rephasing_lobe': gz_slice_selection_rephasing_lobe,
        'gx_imaging_readout_lobe': gx_imaging_readout_lobe,
        'gx_imaging_readout_prephasing_lobe': gx_imaging_readout_prephasing_lobe,
        'gx_imaging_readout_rewinding_lobe': gx_imaging_readout_rewinding_lobe,
        'gx_imaging_crusher': gx_imaging_crusher,
        'gz_imaging_crusher': gz_imaging_crusher,
    })

    # --- Centred interleaved ky ordering ----------------------------------
    # Echo order, starting from the effective TE (stable sort, as MATLAB's).
    echo_indices = np.arange(1, etl + 1)
    echo_order = echo_indices[np.argsort(np.abs(echo_indices - center_echo), kind='stable')]

    # ky order, starting from the k-space centre
    ky_indices = np.arange(1, n_y + 1)
    ky_indices = ky_indices[np.argsort(np.abs(ky_indices - 1 - n_y / 2), kind='stable')]

    ky_order = np.zeros((n_excitations, etl), dtype=int)
    for group in range(1, etl + 1):
        echo = echo_order[group - 1]
        lines = (group - 1) * n_excitations + np.arange(n_excitations)
        ky_order[:, echo - 1] = ky_indices[lines]

    # Every ky line is acquired exactly once
    assert np.array_equal(np.sort(ky_order.ravel()), np.arange(1, n_y + 1)), \
        'Missing or repeated ky lines.'

    # The ky = 0 line is acquired at center_echo
    _, actual_echo = np.nonzero(ky_order == n_y // 2 + 1)
    assert list(actual_echo + 1) == [center_echo], 'Central ky is assigned to the wrong echo.'

    # --- Timing calculations ----------------------------------------------
    t90 = pp.calc_duration(rf90, gz_imaging_slice_selection_lobe)
    t180 = pp.calc_duration(rf180, gz_refocusing_slice_selection_lobe)

    t_reph = pp.calc_duration(gz_slice_selection_rephasing_lobe)
    t_pre = pp.calc_duration(gx_imaging_readout_prephasing_lobe)
    t_rew = pp.calc_duration(gx_imaging_readout_rewinding_lobe)
    t_spoil = pp.calc_duration(gx_imaging_crusher, gz_imaging_crusher)
    t_read = pp.calc_duration(gx_imaging_readout_lobe, adc)

    c90 = rf90.delay + pp.calc_rf_center(rf90)[0]
    c180 = rf180.delay + pp.calc_rf_center(rf180)[0]
    c_adc = adc.delay + readout_time / 2

    # --- Delays -----------------------------------------------------------
    # 90 centre -> first 180 centre
    delay_1 = esp / 2 - (t90 - c90) - t_reph - t_spoil - spoiler_delay - c180
    # 180 centre -> ADC centre
    delay_2 = esp / 2 - (t180 - c180) - spoiler_delay - t_spoil - t_pre - c_adc
    # ADC centre -> next 180 centre
    delay_3 = esp / 2 - (t_read - c_adc) - t_rew - t_spoil - spoiler_delay - c180

    delay_1, delay_2, delay_3 = (np.round(np.array([delay_1, delay_2, delay_3]) / raster) * raster).tolist()
    assert min(delay_1, delay_2, delay_3) >= 0, 'ESP is too short for the selected events.'

    # --- Complete TR ------------------------------------------------------
    t_echo = (t_spoil + spoiler_delay + t180 + spoiler_delay + t_spoil
              + t_pre + delay_2 + t_read + t_rew + delay_3)
    t_train = t90 + t_reph + delay_1 + etl * t_echo

    delay_tr = np.round((tr - t_train) / raster) * raster
    assert delay_tr >= 0, 'TR is too short.'

    # --- TSE acquisition --------------------------------------------------
    for shot in range(n_excitations):
        # Excitation
        seq.add_block(rf90, gz_imaging_slice_selection_lobe)
        seq.add_block(gz_slice_selection_rephasing_lobe)
        if delay_1 > 0:
            seq.add_block(pp.make_delay(delay_1))

        for echo in range(etl):
            # Refocusing and symmetric crushers
            seq.add_block(gx_imaging_crusher, gz_imaging_crusher)
            seq.add_block(pp.make_delay(spoiler_delay))
            seq.add_block(rf180, gz_refocusing_slice_selection_lobe)
            seq.add_block(pp.make_delay(spoiler_delay))
            seq.add_block(gx_imaging_crusher, gz_imaging_crusher)

            # Phase encoding
            ky_index = ky_order[shot, echo]
            ky_area = (ky_index - 1 - n_y / 2) * delta_ky

            if abs(ky_area) > 1e-9:
                gy_imaging_phase_encoding_lobe = pp.make_trapezoid(
                    channel='y', area=ky_area, duration=pre_time, system=system)
                gy_imaging_phase_rewinding_lobe = pp.make_trapezoid(
                    channel='y', area=-ky_area, duration=pre_time, system=system)
                seq.add_block(gx_imaging_readout_prephasing_lobe, gy_imaging_phase_encoding_lobe)
            else:
                seq.add_block(gx_imaging_readout_prephasing_lobe)

            if delay_2 > 0:
                seq.add_block(pp.make_delay(delay_2))

            # Readout
            seq.add_block(gx_imaging_readout_lobe, adc)

            # Rewinding
            if abs(ky_area) > 1e-9:
                seq.add_block(gx_imaging_readout_rewinding_lobe, gy_imaging_phase_rewinding_lobe)
            else:
                seq.add_block(gx_imaging_readout_rewinding_lobe)

            if delay_3 > 0:
                seq.add_block(pp.make_delay(delay_3))

        # Complete TR
        if delay_tr > 0:
            seq.add_block(pp.make_delay(delay_tr))

    # --- Timing verification ----------------------------------------------
    report_lines = mint.report()
    ok, error_report = seq.check_timing()
    if not ok:
        report_lines += [str(e) for e in error_report]
        print('\n'.join(report_lines))
        raise RuntimeError('Invalid Pulseq timing.')
    report_lines.append('Timing check passed successfully.')

    # --- K-space verification ---------------------------------------------
    ktraj_adc, _, _, _, t_adc = seq.calculate_kspace()
    assert ktraj_adc.shape[1] == n_x * n_y, 'Incorrect number of ADC samples.'

    # Measured ky at each ADC centre, in acquisition order
    ky_measured = ktraj_adc[1].reshape(-1, n_x).mean(axis=1)
    ky_expected = ((ky_order - 1 - n_y / 2) * delta_ky).ravel()
    ky_error = np.max(np.abs(ky_measured - ky_expected))

    report_lines += [
        '',
        '--- K-SPACE VERIFICATION ---',
        f'ADC samples    : {ktraj_adc.shape[1]}',
        f'Expected       : {n_x * n_y}',
        f'Max ky error   : {ky_error:.6f} 1/m',
    ]
    assert ky_error < 1e-3, 'Measured ky does not match the prescribed ordering.'

    # --- Measured TE, ESP and TR ------------------------------------------
    t_echo_centres = np.asarray(t_adc).reshape(-1, n_x).mean(axis=1)
    esp_measured = np.diff(t_echo_centres[:etl])
    te_measured = t_echo_centres[center_echo - 1] - (rf90.delay + pp.calc_rf_center(rf90)[0])

    report_lines += [
        '',
        '--- TSE PARAMETERS ---',
        f'Matrix        : {n_x} x {n_y}',
        f'ETL           : {etl}',
        f'Shots         : {n_excitations}',
        f'Effective echo: {center_echo}',
        f'TE prescribed : {te * 1e3:.3f} ms',
        f'TE measured   : {te_measured * 1e3:.3f} ms',
        f'Mean ESP      : {np.mean(esp_measured) * 1e3:.3f} ms',
        f'ESP std       : {np.std(esp_measured) * 1e3:.6f} ms',
    ]
    if n_excitations > 1:
        tr_measured = t_echo_centres[etl] - t_echo_centres[0]
        report_lines.append(f'TR measured   : {tr_measured * 1e3:.3f} ms')
    report_lines.append(f'Scan time     : {n_excitations * tr:.1f} s')

    # --- Run log, .seq and diagram ----------------------------------------
    out_dir = Path(__file__).resolve().parent
    stem = Path(seq_filename).stem

    if test_report:
        report_lines.append(seq.test_report())

    report = '\n'.join(report_lines)
    print(report)
    if save_report:
        report_path = out_dir / f'{stem}_report.txt'
        report_path.write_text(report, encoding='utf-8')
        print(f'Saved report: {report_path}')

    seq.set_definition(key='FOV', value=[fov_x, fov_y, slice_thickness])
    seq.set_definition(key='Name', value='mint_tse_t2_tra')

    if write_seq:
        seq.write(str(out_dir / seq_filename))
        print(f'Wrote {out_dir / seq_filename}')

    if plot or save_plots:
        seq_plot = seq.plot(plot_now=False, time_range=(0, t_train))
        if save_plots:
            for suffix, fig in (('rf_adc', seq_plot.fig1), ('gradients', seq_plot.fig2)):
                png_path = out_dir / f'{stem}_{suffix}.png'
                fig.savefig(png_path, dpi=200, bbox_inches='tight')
                print(f'Saved plot: {png_path}')
        if plot:
            seq_plot.show()
        plt.close('all')

    return seq


if __name__ == '__main__':
    main()
